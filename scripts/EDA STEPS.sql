-- STEP 5 - MAGNITUDE ANALYSIS (MEASURES BY DIMENSIONS)

-- total customers by country 
SELECT 
	country,
	COUNT([customer_key]) AS Total_customers
FROM gold.dim_customers
GROUP BY country
ORDER BY Total_customers DESC 


-- total customers by gender 
SELECT 
	gender,
	COUNT([customer_key]) AS Total_customers_by 
FROM gold.dim_customers
GROUP BY gender
ORDER BY Total_customers_by DESC


-- total products by category 
SELECT 
	category,
	COUNT(product_key) AS total_product
FROM gold.dim_products
GROUP BY category
ORDER BY total_product DESC


-- Average cost by category 
SELECT 
	category,
	AVG(cost) AS Average_cost 
FROM gold.dim_products
GROUP BY category
ORDER BY Average_cost DESC


-- Total revenue genrated by each catgory 
SELECT 
pr.category,
SUM(fs.sales_amount) AS Total_sales_by_products 
FROM gold.fact_sales AS fs
LEFT JOIN gold.dim_products AS pr
ON fs.product_key = pr.product_key
GROUP BY pr.category
ORDER BY Total_sales_by_products DESC


--Total revenue generated by each customer [customer_key][customer_id]
	SELECT 
		cu.customer_key,
		cu.first_name,
		cu.last_name,
		SUM(sales_amount) AS Total_revenue_by_customer
	FROM gold.dim_customers AS cu
	LEFT JOIN gold.fact_sales AS fs
	ON cu.customer_key = fs.customer_key
	GROUP BY  cu.customer_key,
			  cu.first_name,
			  cu.last_name		
	ORDER BY Total_revenue_by_customer desc


-- distribution of items sold across countries ?
SELECT 
	cu.country,
	SUM(fs.quantity) AS total_items_sold_by_country
FROM gold.dim_customers AS cu
LEFT JOIN gold.fact_sales AS fs
ON cu.customer_key = fs.customer_key
GROUP BY cu.country
ORDER BY total_items_sold_by_country DESC

