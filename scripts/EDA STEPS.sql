-- STEP 3 - DATE EXPLORATION
-- customers table
	SELECT 
		MAX(birthdate) AS oldest_customer,
		MIN(birthdate) AS yougest_customer
	FROM gold.dim_customers ;

	SELECT 
		MAX(create_date) AS newest_date,
		MIN(create_date) AS oldest_date
	FROM gold.dim_customers;

-- products table 
	SELECT 
		MAX(start_date) newest_product_date,
		MIN(start_date) oldest_product_date
	FROM gold.dim_products;

-- sales table
	SELECT 
		MAX(due_date) AS highest_due_date,
		MIN(due_date) AS oldest_due_date
	FROM gold.fact_sales;

	SELECT 
		MAX(shipping_date) AS highest_ship_date,
		MIN(shipping_date) AS lowest_ship_date
	FROM gold.fact_sales;

	SELECT 
		MAX(order_date) AS highest_order_date,
		MIN(order_date) AS lowest_order_date
	FROM gold.fact_sales;

