--STEP 6 - RANKING (DIMENSIONS BY MEASURES)

--which 5 product genrate the highest revenue ?
SELECT TOP 5 
	pr.product_name,
	SUM(sls.sales_amount) AS revenue
FROM gold.dim_products AS pr
LEFT JOIN gold.fact_sales AS sls
ON pr.product_key = sls.product_key
GROUP BY pr.product_name 
ORDER BY revenue ASC


--which 5 product generate the worst revenue ?
SELECT TOP 5 
	pr.product_name,
	SUM(sls.sales_amount) AS revenue
FROM gold.dim_products AS pr
LEFT JOIN gold.fact_sales AS sls
ON pr.product_key = sls.product_key
GROUP BY pr.product_name 
ORDER BY revenue ASC


--top 10 customers with highest revenue
SELECT TOP 10	
	cu.first_name,
	cu.last_name,
	SUM(fs.sales_amount) AS revenue_generated 
FROM gold.dim_customers AS cu
LEFT JOIN gold.fact_sales AS fs
ON cu.customer_key = fs.customer_key
GROUP BY cu.first_name,
	     cu.last_name
ORDER BY revenue_generated DESC
